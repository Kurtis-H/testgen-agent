"""Turn verified test cases into a plain pytest file anyone can read and run.

Values are written with repr(), so whatever text the model produced ends up as a Python
literal: data, never code.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from testgen_agent.cases import TestCase

CONFTEST = '''"""Shared helpers for generated API tests. Set API_URL to point at the server."""

import os
import uuid

import httpx
import pytest


@pytest.fixture(scope="session")
def client():
    with httpx.Client(base_url=os.environ.get("API_URL", "http://127.0.0.1:3000"), timeout=15) as c:
        yield c


def fill(value):
    if isinstance(value, str):
        value = value.replace("{{unique_email}}", f"tg-{uuid.uuid4().hex[:10]}@example.com")
        return value.replace("{{unique_name}}", f"user-{uuid.uuid4().hex[:6]}")
    if isinstance(value, dict):
        return {k: fill(v) for k, v in value.items()}
    if isinstance(value, list):
        return [fill(v) for v in value]
    return value


def get_path(data, dotted):
    cur = data
    for part in dotted.split("."):
        if part == "length":
            cur = len(cur)
        elif isinstance(cur, list):
            cur = cur[int(part)]
        else:
            cur = cur[part]
    return cur
'''


def render_case(case: TestCase) -> str:
    lines = [f"def test_{case.name}(client):"]
    if case.why:
        lines.append(f"    # {case.why.replace(chr(10), ' ')}")
    args = [repr(case.method), repr(case.path)]
    if case.query:
        args.append(f"params={case.query!r}")
    if case.body is not None:
        args.append(f"json=fill({case.body!r})")
    lines.append(f"    r = client.request({', '.join(args)})")
    lines.append(f"    assert r.status_code == {case.expect_status!r}, r.text")
    if case.expect_json:
        lines.append("    body = r.json()")
        for path, value in case.expect_json.items():
            lines.append(f"    assert get_path(body, {path!r}) == {value!r}")
    return "\n".join(lines)


def write_tests(cases: list[TestCase], out_dir: str | Path) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "conftest.py").write_text(CONFTEST, encoding="utf-8")
    by_op: dict[str, list[TestCase]] = defaultdict(list)
    for c in cases:
        by_op[c.operation_id].append(c)
    written = []
    for op_id, op_cases in sorted(by_op.items()):
        seen: dict[str, int] = defaultdict(int)
        bodies = []
        for c in op_cases:
            seen[c.name] += 1
            if seen[c.name] > 1:
                c.name = f"{c.name}_{seen[c.name]}"
            bodies.append(render_case(c))
        header = (
            f'"""Generated by testgen-agent for operation {op_id!r}.\n\n'
            "Every test here was run against the live API and passed 3 times in a row before\n"
            'being written. Review before committing: passing is not the same as correct."""\n\n'
            "from conftest import fill, get_path  # noqa: F401\n\n\n"
        )
        safe = "".join(ch if ch.isalnum() else "_" for ch in op_id).lower()
        path = out / f"test_{safe}.py"
        path.write_text(header + "\n\n\n".join(bodies) + "\n", encoding="utf-8")
        written.append(path)
    return written
